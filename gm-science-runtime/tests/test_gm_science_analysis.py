from __future__ import annotations

import json
import time
from pathlib import Path

import pytest

from openppx.gm_science.analysis.config import AnalysisConfig, parse_analysis_config
from openppx.gm_science.analysis.service import AnalysisService
from openppx.gm_science.data.config import DatasetConfig
from openppx.gm_science.data.service import DatasetService
from openppx.gm_science.execution.config import ScienceExecutionConfig
from openppx.gm_science.execution.service import ScienceExecutionService
from openppx.gm_science.store import GmScienceStore


def _services(tmp_path: Path) -> tuple[AnalysisService, DatasetService, ScienceExecutionService, GmScienceStore, str]:
    state = tmp_path / "state"
    store = GmScienceStore(state)
    project = store.create_project(name="Analysis", description="", agent_context="")
    datasets = DatasetService(
        store=store,
        config=DatasetConfig(
            enabled=True,
            max_file_size_bytes=1_000_000,
            profile_row_limit=1_000,
            preview_rows=10,
            max_columns=50,
            top_values_limit=10,
        ),
    )
    execution = ScienceExecutionService(
        data_dir=state,
        store=store,
        config=ScienceExecutionConfig(
            enabled=True,
            python_executable="",
            max_concurrent_runs=2,
            default_timeout_seconds=10,
            max_source_chars=200_000,
            max_log_preview_chars=6_000,
        ),
    )
    analysis = AnalysisService(
        store=store,
        dataset_service=datasets,
        execution_service=execution,
        config=AnalysisConfig(
            enabled=True,
            max_datasets=3,
            max_objective_chars=4_000,
            max_numeric_columns=20,
            max_group_categories=20,
        ),
    )
    return analysis, datasets, execution, store, project.id


def _wait(analysis: AnalysisService, project_id: str, analysis_id: str) -> dict:
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        payload = analysis.get_analysis(project_id, analysis_id)
        if payload["status"] in {"completed", "failed", "cancelled", "lost"}:
            return payload
        time.sleep(0.05)
    raise AssertionError(f"Analysis {analysis_id} did not finish")


