def test_analysis_rejects_foreign_or_changed_dataset(tmp_path: Path) -> None:
    analysis, datasets, _execution, store, project_id = _services(tmp_path)
    other = store.create_project(name="Other", description="", agent_context="")
    source = tmp_path / "study.csv"
    source.write_text("x\n1\n2\n", encoding="utf-8")
    dataset = datasets.import_dataset(project_id=project_id, source_path=str(source))

    with pytest.raises(ValueError, match="was not found"):
        analysis.create_draft(
            project_id=other.id,
            objective="Analyze data.",
            dataset_artifact_ids=[dataset["artifact_id"]],
        )

    draft = analysis.create_draft(
        project_id=project_id,
        objective="Analyze data.",
        dataset_artifact_ids=[dataset["artifact_id"]],
    )
    Path(dataset["path"]).write_text("x\n999\n", encoding="utf-8")
    with pytest.raises(ValueError, match="changed after profiling"):
        analysis.run_analysis(project_id, draft["id"])


